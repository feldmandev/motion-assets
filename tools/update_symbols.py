"""Update all Material Symbols styles from one immutable Google revision."""
import argparse
import io
import json
from pathlib import Path
import re
from urllib.parse import quote
from urllib.request import Request, urlopen

from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
STYLES = ("rounded", "outlined", "sharp")


def download(url):
    with urlopen(Request(url, headers={"User-Agent": "motion-assets"}), timeout=120) as response:
        return response.read()


def names_in_font(font):
    """Keep legacy ligatures as well as the current codepoint names."""
    characters = {glyph: chr(code) for code, glyph in font.getBestCmap().items()}
    result = {}
    for lookup in font["GSUB"].table.LookupList.Lookup:
        for table in lookup.SubTable:
            table = getattr(table, "ExtSubTable", table)
            for first, ligatures in getattr(table, "ligatures", {}).items():
                for ligature in ligatures:
                    spelling = "".join(characters.get(glyph, "") for glyph in [first, *ligature.Component])
                    if re.fullmatch(r"[a-z0-9_]+", spelling):
                        result[spelling] = ligature.LigGlyph
    return result


def kotlin(names):
    output = ROOT / "integrations/android"
    output.mkdir(parents=True, exist_ok=True)
    constants = [f'    const val ic_{"_" if name[0].isdigit() else ""}{name} = "{name}"' for name in names]
    rows = ["        " + ", ".join(json.dumps(name) for name in names[i:i + 6]) + "," for i in range(0, len(names), 6)]
    header = "// Generated by motion-assets/tools/update_symbols.py. Do not edit.\n"
    (output / "MotionSymbols.kt").write_text('@file:Suppress("ConstPropertyName")\n\npackage com.feldman.motion\n\n' + header +
        "object MotionSymbols {\n" + "\n".join(constants) + "\n    val all: List<String> = listOf(\n" + "\n".join(rows) + "\n    )\n}\n", encoding="utf-8", newline="\n")
    properties = []
    seen = set()
    for name in names:
        prop = "".join(word[:1].upper() + word[1:] for word in name.split("_"))
        prop = ("_" if prop[0].isdigit() else "") + prop
        if prop in seen:
            raise ValueError(f"Kotlin property collision: {prop}")
        seen.add(prop)
        properties.append(f'    val {prop}: MotionSymbol get() = MotionSymbol("{name}", fill)')
    (output / "MotionIcons.kt").write_text("package com.feldman.motion\n\n" + header +
        "object MotionIcons {\n    val Filled = MotionIconSet(1f)\n    val Outlined = MotionIconSet(0f)\n    val Default = Filled\n}\n\n" +
        "class MotionIconSet internal constructor(private val fill: Float) {\n" + "\n".join(properties) + "\n}\n", encoding="utf-8", newline="\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--latest", action="store_true", help="Resolve Google's current master commit before downloading")
    args = parser.parse_args()
    lock_path = ROOT / "symbols-upstream.json"
    lock = json.loads(lock_path.read_text())
    if args.latest:
        lock["ref"] = json.loads(download("https://api.github.com/repos/google/material-design-icons/commits/master"))["sha"]
    revision = lock["ref"]
    if not re.fullmatch(r"[a-f0-9]{40}", revision):
        raise ValueError("Symbols must be pinned to a full commit SHA")
    base = f"https://raw.githubusercontent.com/{lock['repository']}/{revision}/"
    prepared = {}
    catalogs = {}
    for style in STYLES:
        upstream = f"MaterialSymbols{style.title()}[FILL,GRAD,opsz,wght]"
        font_bytes = download(base + "variablefont/" + quote(upstream + ".ttf"))
        codepoints = download(base + "variablefont/" + quote(upstream + ".codepoints"))
        font = TTFont(io.BytesIO(font_bytes), recalcTimestamp=False)
        if {axis.axisTag for axis in font["fvar"].axes} != {"FILL", "GRAD", "opsz", "wght"}:
            raise ValueError(f"Unexpected variable axes: {style}")
        names = {}
        cmap = font.getBestCmap()
        for line in codepoints.decode().splitlines():
            name, code = line.split()
            if not re.fullmatch(r"[a-z0-9_]+", name) or int(code, 16) not in cmap:
                raise ValueError(f"Invalid codepoint entry: {style}/{name}")
            names[name] = int(code, 16)
        aliases = names_in_font(font)
        reverse = {glyph: code for code, glyph in cmap.items() if code >= 0xE000}
        for name, glyph in aliases.items():
            if glyph in reverse:
                names.setdefault(name, reverse[glyph])
        if not names:
            raise ValueError("Empty Symbols catalog")
        catalogs[style] = dict(sorted(names.items()))
        prepared[f"material_symbols_{style}.ttf"] = font_bytes
        prepared[f"material_symbols_{style}.codepoints"] = codepoints
        font.flavor = "woff2"
        buffer = io.BytesIO()
        font.save(buffer)
        prepared[f"material_symbols_{style}.woff2"] = buffer.getvalue()
    prepared["upstream.json"] = (json.dumps(lock, indent=2) + "\n").encode()
    prepared["catalog.json"] = (json.dumps({"revision": revision, "styles": catalogs}, indent=2) + "\n").encode()
    license_bytes = download(base + "LICENSE")
    for name, content in prepared.items():
        (ROOT / "assets/symbols" / name).write_bytes(content)
    (ROOT / "LICENSES/Apache-2.0.txt").write_bytes(license_bytes)
    lock_path.write_text(json.dumps(lock, indent=2) + "\n")
    kotlin(sorted(catalogs["rounded"]))
    print(f"Material Symbols {revision}: " + ", ".join(f"{style}={len(names)}" for style, names in catalogs.items()))


if __name__ == "__main__":
    main()
